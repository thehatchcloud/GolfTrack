package backup

import (
	"bytes"
	"encoding/json"
	"fmt"
	"path"
	"path/filepath"
	"strconv"
)

// Databases are the SQLite files PocketBase keeps in its data directory, each
// with the name of its own folder at the destination. data.db holds the six
// GolfTrack collections; auxiliary.db holds request and cron logs.
var Databases = []struct {
	File    string
	Replica string
}{
	{"data.db", "data"},
	{"auxiliary.db", "auxiliary"},
}

// Files written next to the rendered config, in the runtime directory.
const (
	RenderedConfigFile = "litestream.yml"
	SocketFile         = "litestream.sock"
	sftpKeyFile        = "sftp_key"
	gcsCredentialsFile = "gcs.json"
)

// Rendered is everything Litestream needs to run one config. It holds
// decrypted credentials, so it is written with mode 0600 to the runtime
// directory only while Litestream runs (#174), and removed after.
type Rendered struct {
	// Files maps a file name in the runtime directory to its contents. It
	// always includes RenderedConfigFile.
	Files map[string][]byte

	// Env is extra environment for the Litestream process, as KEY=value.
	Env []string
}

// Render produces the Litestream config for cfg. dataDir is the PocketBase
// data directory (where the databases are) and runDir the directory the
// files will be written to; both must be absolute, because Litestream is
// given the paths as-is.
//
// The YAML uses Litestream v0.5's single `replica:` block per database (the
// `replicas:` list is deprecated). Every string is written double-quoted
// with JSON escaping — valid YAML that keeps any character in a password
// literal. Litestream must be run with -no-expand-env so that a "$" in a
// credential is not read as an environment variable.
func Render(cfg Config, dataDir, runDir string) (Rendered, error) {
	if cfg.Kind == KindNone || cfg.Kind == "" {
		return Rendered{}, fmt.Errorf("render backup config: backups are off")
	}
	if !cfg.complete() {
		return Rendered{}, fmt.Errorf("render backup config: %s destination has no settings", cfg.Kind)
	}
	if !filepath.IsAbs(dataDir) || !filepath.IsAbs(runDir) {
		return Rendered{}, fmt.Errorf("render backup config: data and runtime directories must be absolute")
	}

	r := Rendered{Files: map[string][]byte{}}

	var w yamlWriter
	w.comment("Generated by golftrack-pb from the backup setting (" + cfg.Summary() + ").")
	w.comment("Rewritten every time Litestream starts; edits here are lost.")
	w.key(0, "dbs")
	for _, db := range Databases {
		w.listItem(1, "path", filepath.Join(dataDir, db.File))
		w.key(2, "replica")
		fields, err := replicaFields(cfg, db.Replica, runDir, &r)
		if err != nil {
			return Rendered{}, err
		}
		for _, f := range fields {
			w.field(3, f.k, f.v)
		}
	}
	if cfg.KeepOldBackups {
		w.key(0, "retention")
		w.field(1, "enabled", false)
	}
	// The control socket lets the status page ask Litestream how
	// replication is going (GET /list, GET /info). Permissions are written
	// in decimal (384 = 0600) so no YAML version can read them differently.
	w.key(0, "socket")
	w.field(1, "enabled", true)
	w.field(1, "path", filepath.Join(runDir, SocketFile))
	w.field(1, "permissions", 0o600)

	r.Files[RenderedConfigFile] = w.Bytes()
	return r, nil
}

type kv struct {
	k string
	v any
}

func replicaFields(cfg Config, name, runDir string, r *Rendered) ([]kv, error) {
	switch cfg.Kind {
	case KindFile:
		return []kv{
			{"type", "file"},
			{"path", filepath.Join(cfg.File.Path, name)},
		}, nil

	case KindSFTP:
		s := cfg.SFTP
		port := s.Port
		if port == 0 {
			port = 22
		}
		f := []kv{
			{"type", "sftp"},
			{"host", s.Host + ":" + strconv.Itoa(port)},
			{"user", s.User},
		}
		if s.PrivateKey != "" {
			key := s.PrivateKey
			if key[len(key)-1] != '\n' {
				key += "\n" // OpenSSH rejects a key file without the final newline
			}
			r.Files[sftpKeyFile] = []byte(key)
			f = append(f, kv{"key-path", filepath.Join(runDir, sftpKeyFile)})
		} else {
			f = append(f, kv{"password", s.Password})
		}
		if s.HostKey != "" {
			f = append(f, kv{"host-key", s.HostKey})
		}
		return append(f, kv{"path", path.Join(s.Path, name)}), nil

	case KindS3:
		s := cfg.S3
		f := []kv{
			{"type", "s3"},
			{"bucket", s.Bucket},
			{"path", path.Join(s.Path, name)},
		}
		if s.Region != "" {
			f = append(f, kv{"region", s.Region})
		}
		if s.Endpoint != "" {
			f = append(f, kv{"endpoint", s.Endpoint})
		}
		if s.ForcePathStyle {
			f = append(f, kv{"force-path-style", true})
		}
		if s.SkipVerify {
			f = append(f, kv{"skip-verify", true})
		}
		return append(f,
			kv{"access-key-id", s.AccessKeyID},
			kv{"secret-access-key", s.SecretAccessKey},
		), nil

	case KindGCS:
		// Litestream has no config field for GCS credentials: it uses
		// Google's Application Default Credentials, pointed at a key file
		// by GOOGLE_APPLICATION_CREDENTIALS.
		credPath := filepath.Join(runDir, gcsCredentialsFile)
		r.Files[gcsCredentialsFile] = []byte(cfg.GCS.ServiceAccountJSON)
		r.Env = []string{"GOOGLE_APPLICATION_CREDENTIALS=" + credPath}
		return []kv{
			{"type", "gs"},
			{"bucket", cfg.GCS.Bucket},
			{"path", path.Join(cfg.GCS.Path, name)},
		}, nil

	case KindABS:
		a := cfg.ABS
		f := []kv{
			{"type", "abs"},
			{"account-name", a.AccountName},
		}
		if a.SASToken != "" {
			f = append(f, kv{"sas-token", a.SASToken})
		} else {
			f = append(f, kv{"account-key", a.AccountKey})
		}
		f = append(f,
			kv{"bucket", a.Container},
			kv{"path", path.Join(a.Path, name)},
		)
		if a.Endpoint != "" {
			f = append(f, kv{"endpoint", a.Endpoint})
		}
		return f, nil
	}
	return nil, fmt.Errorf("render backup config: unsupported kind %q", cfg.Kind)
}

// yamlWriter writes the small block-style YAML subset the config needs.
type yamlWriter struct {
	bytes.Buffer
}

func (w *yamlWriter) indent(level int) {
	for range level {
		w.WriteString("  ")
	}
}

func (w *yamlWriter) comment(s string) {
	w.WriteString("# " + s + "\n")
}

func (w *yamlWriter) key(level int, k string) {
	w.indent(level)
	w.WriteString(k + ":\n")
}

func (w *yamlWriter) listItem(level int, k string, v any) {
	w.indent(level)
	w.WriteString("- " + k + ": " + scalar(v) + "\n")
}

func (w *yamlWriter) field(level int, k string, v any) {
	w.indent(level)
	w.WriteString(k + ": " + scalar(v) + "\n")
}

// scalar renders a value. Strings are JSON-quoted: a JSON string is also a
// valid YAML double-quoted scalar, so nothing in a value can break out of it.
func scalar(v any) string {
	switch v := v.(type) {
	case bool:
		return strconv.FormatBool(v)
	case int:
		return strconv.Itoa(v)
	case string:
		b, _ := json.Marshal(v)
		return string(b)
	default:
		panic(fmt.Sprintf("backup: unsupported YAML value %T", v))
	}
}
